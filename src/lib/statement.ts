export function statementToText(s: Statement) {
  return [
    ...s.addressee,
    "",
    ...s.sender,
    "",
    s.title,
    s.subtitle,
    "",
    ...s.paragraphs,
    "",
    "На основании изложенного ПРОШУ:",
    ...s.requests.map((r, i) => `${i + 1}. ${r}`),
    "",
    "Приложения:",
    ...s.attachments.map((a, i) => `${i + 1}. ${a}`),
    "",
    `Дата: ${s.date}`,
    `Подпись: ${s.signature}`,
  ].join("\n");
}


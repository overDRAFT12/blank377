export function fileNameFor(c: Contract, index: number) {
  const base = (c.creditorName || `Кредитор ${index + 1}`)
    .replace(/[«»"“”]/g, "")
    .replace(/[\\/:*?<>|]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 60);
  const num = c.number ? `_${c.number.replace(/[\\/:*?<>|\s]+/g, "-")}` : "";
  return `${String(index + 1).padStart(2, "0")}_${base}${num}.docx`;
}



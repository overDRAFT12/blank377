const v = (s: string, fallback = "________") => (s && s.trim() ? s.trim() : fallback);

/** Normalize absent optional values at the document boundary, not in the PDF parser. */
function documentFields<T extends object>(fields: T): T {
  return Object.fromEntries(Object.entries(fields).map(([key, value]) => [key,
    value == null || (typeof value === "number" && !Number.isFinite(value)) ? "" : typeof value === "string"
      ? (/^(?:undefined|null|NaN)$/i.test(value.trim()) ? "" : value.trim()) : value,
  ])) as T;
}

function contractDetails(c: Contract) {
  return `${c.number ? ` № ${c.number}` : ""}${c.date ? ` от ${c.date}` : ""}`;
}

export function formatToday(d = new Date()) {
  return d.toLocaleDateString("ru-RU", { day: "2-digit", month: "2-digit", year: "numeric" });
}

function shortName(full: string) {
  const [last, first, middle] = full.trim().split(/\s+/);
  if (!last) return "________";
  return [last, first ? `${first[0]}.` : "", middle ? `${middle[0]}.` : ""].join(" ").replace(/\s+$/, "");
}

export function contractRef(c: Contract) {
  c = documentFields(c);
  const parts = [`договор${contractDetails(c)}`];
  if (c.uid) parts.push(`УИд ${c.uid}`);
  return parts.join(" ");
}

/** Реквизиты паспорта в одну строку: «серия … № …, выдан … …, код подразделения …». */
function passportLine(person: Person) {
  const issued = [v(person.passportIssuedBy), person.passportIssueDate.trim()].filter(Boolean).join(" ");
  const code = person.passportCode ? `, код подразделения ${person.passportCode}` : "";
  const prev = documentPerson(person).previousPassport.trim() ? ` (ранее выдавался паспорт ${person.previousPassport.trim()})` : "";
  return `Паспорт: серия ${v(person.passportSeries, "____")} № ${v(person.passportNumber, "______")}, выдан ${issued}${code}${prev}`;
}

/** Шапка «От: …» — одинаковая для кредиторов и ФССП. */
export function senderLines(person: Person) {
  return [
    `От: ${v(person.fullName)}`,
    `Дата рождения: ${v(person.birthDate)}`,
    passportLine(person),
    `Адрес регистрации: ${v(person.address)}`,
    ...(person.phone ? [`Тел.: ${person.phone}`] : []),
    ...(person.email ? [`Email: ${person.email}`] : []),
  ];
}

